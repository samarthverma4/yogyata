"""Evaluate university analytics: planted-gap recovery and privacy (suppression) invariants.

Usage: python scripts/evaluate_analytics.py [--out reports/analytics_eval.json]
Synthetic cohorts are generated with a fixed seed. Because the data is generated by this script, 'recovery' only checks
that the aggregation arithmetic is right; it says nothing about real cohorts. Privacy invariants are the real point:
  S1 no released group below k; S2 pooled group >= k; S3 no skill rate over < k assessed students, no placement rate over < k known;
  S4 subtraction attack: overall n minus released group n's is 0 or >= k; S5 no identifiers leak into the output.
"""
from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from yogyata_ai.university_analytics import cohort_analytics  # noqa: E402

DEPTS = ["CSE", "ECE", "MECH", "CIVIL", "IT", "EEE"]


def make(rng, sizes, planted):
    recs = []
    for d, n in sizes.items():
        for i in range(n):
            weak = planted.get(d)
            ev = []
            for sk in ("SQL", "Python", "Statistics"):
                bad = sk == weak and rng.random() < 0.8
                ev.append({"skill": sk, "source": "interview_auto", "strength": round(rng.uniform(0.1, 0.3) if bad else rng.uniform(0.65, 0.95), 2),
                           "ref_id": f"{d}-{i}-{sk}"})
            recs.append({"department": d, "graduation_year": 2027, "target_role": "data_analyst",
                         "profile": {"student_id": f"SECRET-{d}-{i}", "evidence": ev}, "placed": rng.choice([True, False, None])})
    return recs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out")
    args = ap.parse_args()
    rng = random.Random(7)
    # (1) planted-gap recovery on a cohort with all groups >= k
    planted = {"CSE": "SQL", "ECE": "Python", "IT": "Statistics"}
    out = cohort_analytics(make(rng, {"CSE": 30, "ECE": 25, "IT": 20}, planted), k=10)
    rec_ok = {g["label"]: (g["top_gaps"][:1] == [planted[g["label"]]]) for g in out["groups"]}
    # (2) missing != poor
    unassessed = cohort_analytics([{"department": "CSE", "target_role": "data_analyst", "profile": {}} for _ in range(20)], k=10)
    ua = unassessed["groups"][0]
    missing_ok = ua["top_gaps"] == [] and ua["skill_rows"] == [] and ua["evidence_sufficiency_share"]["low"] == 1.0
    # (3) privacy invariants over random cohorts
    res = {k: [0, 0] for k in ("S1", "S2", "S3", "S4", "S5")}
    K = 10
    for _ in range(200):
        sizes = {d: rng.choice([0, 1, 2, 3, 5, 9, 10, 11, 15, 30]) for d in DEPTS}
        sizes = {d: n for d, n in sizes.items() if n}
        recs = make(rng, sizes, {"CSE": "SQL"})
        o = cohort_analytics(recs, k=K)
        blob = json.dumps(o)
        res["S5"][1] += 1
        res["S5"][0] += "SECRET" not in blob
        released = o["groups"] + ([o["pooled"]] if o["pooled"] else []) + ([o["overall"]] if o["overall"] else [])
        res["S1"][1] += 1
        res["S1"][0] += all(g["n"] >= K for g in released)
        res["S2"][1] += 1
        res["S2"][0] += (o["pooled"] is None or o["pooled"]["n"] >= K)
        res["S3"][1] += 1
        res["S3"][0] += all(all(r["assessed_n"] >= K for r in g["skill_rows"]) and (("suppressed" in g["placement"]) or g["placement"]["known_outcome_n"] >= K) for g in released)
        res["S4"][1] += 1
        if o["overall"]:
            rest = o["overall"]["n"] - sum(g["n"] for g in o["groups"]) - (o["pooled"]["n"] if o["pooled"] else 0)
            # anything not released as a group must be unreachable: either nothing is hidden, or the hidden remainder is >= k
            res["S4"][0] += rest == 0 or rest >= K
        else:
            res["S4"][0] += sum(sizes.values()) < K
    rep = {"disclaimer": "Synthetic cohorts generated by this script (seed 7). Checks aggregation arithmetic and privacy invariants only.",
           "planted_gap_recovered_top1": rec_ok, "all_unassessed_cohort_reports_no_weaknesses": missing_ok,
           "privacy_invariants_over_200_random_cohorts": {k: f"{a}/{b}" for k, (a, b) in res.items()},
           "all_privacy_invariants_hold": all(a == b for a, b in res.values())}
    text = json.dumps(rep, indent=2)
    print(text)
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
